"""Small preview images of all bodies for the space view: two atlases instead of one texture per body.

  python3 scripts/planet-atlas.py

Reads the textures of all bodies in src/space/bodies.ts (the sharper 8k maps are replaced by the
2k maps in PREFER) and writes
  public/textures/planet-atlas.jpg   centre square of each map, the round thumbnails of the body list
  public/textures/planet-lowres.jpg  each whole map at 256 × 128, shown on the 3D body until its
                                     full texture is loaded (when it is big on screen or selected)
plus src/space/atlas.ts (the id → cell table). Re-run when a body or texture is added. Needs Pillow.
"""

import math
import os
import re

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEX = os.path.join(ROOT, 'public', 'textures')
CELL = 96  # 2 × the 40 px list thumbnail
COLS = 8
LOW_W, LOW_H, LOW_COLS = 256, 128, 4
PREFER = {
    'sun': 'sunmap.jpg',
    'mercury': 'mercurymap.jpg',
    'venus': 'venusmap.jpg',
    'earth': 'earthmap2k.jpg',
    'moon': 'moonmap2k.jpg',
    'mars': 'marsmap2k.jpg',
    'jupiter': 'jupitermap.jpg',
    'saturn': 'saturnmap.jpg',
}


def body_textures() -> dict[str, str]:
    out: dict[str, str] = {}
    cur = None
    with open(os.path.join(ROOT, 'src', 'space', 'bodies.ts'), encoding='utf-8') as f:
        for line in f:
            m = re.match(r"^ {4}id: '([a-z0-9_-]+)'", line)
            if m:
                cur = m.group(1)
                continue
            m = re.match(r"^ {4}texture: tex\('([^']+)'\)", line)
            if m and cur:
                out[cur] = m.group(1)
    return out


def main():
    tex = body_textures()
    ids = list(tex)
    rows = math.ceil(len(ids) / COLS)
    low_rows = math.ceil(len(ids) / LOW_COLS)
    sheet = Image.new('RGB', (COLS * CELL, rows * CELL), (34, 42, 68))
    low = Image.new('RGB', (LOW_COLS * LOW_W, low_rows * LOW_H), (34, 42, 68))
    for i, bid in enumerate(ids):
        im = Image.open(os.path.join(TEX, PREFER.get(bid, tex[bid]))).convert('RGB')
        w, h = im.size
        side = min(w, h)
        left, top = (w - side) // 2, (h - side) // 2
        sq = im.crop((left, top, left + side, top + side)).resize((CELL, CELL), Image.LANCZOS)
        sheet.paste(sq, ((i % COLS) * CELL, (i // COLS) * CELL))
        low.paste(im.resize((LOW_W, LOW_H), Image.LANCZOS), ((i % LOW_COLS) * LOW_W, (i // LOW_COLS) * LOW_H))
    for name, img in (('planet-atlas.jpg', sheet), ('planet-lowres.jpg', low)):
        out = os.path.join(TEX, name)
        img.save(out, quality=82, optimize=True, progressive=True)
        print(f'{out}: {len(ids)} cells, {os.path.getsize(out) // 1024} kB')

    with open(os.path.join(ROOT, 'src', 'space', 'atlas.ts'), 'w', encoding='utf-8') as f:
        f.write("// Generated by scripts/planet-atlas.py – do not edit.\n")
        f.write("// Cell of every textured body in public/textures/planet-atlas.jpg (list thumbnails in the space view)\n")
        f.write("// and planet-lowres.jpg (preview textures of the 3D bodies).\n\n")
        f.write(f"export const ATLAS = {{ cell: {CELL}, cols: {COLS}, rows: {rows} }};\n")
        f.write(f"export const LOWRES = {{ w: {LOW_W}, h: {LOW_H}, cols: {LOW_COLS}, rows: {low_rows} }};\n\n")
        f.write("export const ATLAS_CELL: Record<string, number> = {\n")
        for i, bid in enumerate(ids):
            f.write(f"  {bid}: {i},\n")
        f.write("};\n")


main()
