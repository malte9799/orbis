// Regional HiRISE / CTX image mosaics of NASA Mars Trek (landing sites, rover areas, quads).
// Reads Trek's own search index and the WMTS capabilities of every product, keeps the
// image mosaics (no DEMs, hillshades, slopes, spectral products) and writes
// src/space/mars-mosaics.ts. Run: node scripts/mars-mosaics.mjs

import { writeFileSync } from 'node:fs';

const SEARCH = 'https://trek.nasa.gov/mars/TrekServices/ws/index/eq/searchItems?proj=eq&rows=500&start=';
const get = async (url) => {
  const r = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r;
};

const docs = [];
for (let s = 0; s < 3000; s += 500) {
  const d = await (await get(SEARCH + s)).json();
  docs.push(...d.response.docs);
  if (d.response.docs.length < 500) break;
}
const products = docs.filter((x) => (x.itemType === 'product' || x.itemType === 'dataset') && x.productLabel);

const isMosaic = (t) => {
  if (/DEM|Hill+shade|Shade|Slope|CRISM|TES|Global|Roughness|Albedo|Indicator/i.test(t)) return false;
  if (/^MRO HiRISE,/.test(t)) return /Mosaic/i.test(t);
  if (/^MRO CTX,/.test(t) || /^Mars Reconnaissance Orbiter CTX, Mosaic/.test(t)) return /Mosaic/i.test(t);
  return /^MSL, /.test(t);
};

const out = [];
let i = 0;
await Promise.all(
  Array.from({ length: 12 }, async () => {
    while (i < products.length) {
      const x = products[i++];
      if (!isMosaic(x.title ?? '')) continue;
      try {
        const t = await (await get(`https://trek.nasa.gov/tiles/Mars/EQ/${x.productLabel}/1.0.0/WMTSCapabilities.xml`)).text();
        const bb = /<ows:WGS84BoundingBox[^>]*>\s*<ows:LowerCorner>([-\d.eE ]+)<\/ows:LowerCorner>\s*<ows:UpperCorner>([-\d.eE ]+)<\/ows:UpperCorner>/.exec(t);
        const ids = [...t.matchAll(/<TileMatrix><ows:Identifier>(\d+)</g)].map((m) => +m[1]);
        const fmt = /<Format>image\/(\w+)<\/Format>/.exec(t)?.[1];
        if (!bb || !ids.length || !fmt) continue;
        const [w, s] = bb[1].trim().split(/\s+/).map(Number);
        const [e, n] = bb[2].trim().split(/\s+/).map(Number);
        if (e - w > 100) continue; // global product
        if (Math.max(...ids) < 13) continue; // not sharper than the global 5 m CTX mosaic
        out.push({ label: x.productLabel, title: x.title.replace(/^Mars Reconnaissance Orbiter CTX, /, 'MRO CTX, '), fmt: fmt === 'jpeg' ? 'jpg' : fmt, bbox: [w, s, e, n].map((v) => Math.round(v * 1e4) / 1e4), maxZ: Math.max(...ids) });
      } catch {
        /* layer not served */
      }
    }
  }),
);

// finest on top: by detail, larger footprints first
out.sort((a, b) => a.maxZ - b.maxZ || (b.bbox[2] - b.bbox[0]) * (b.bbox[3] - b.bbox[1]) - (a.bbox[2] - a.bbox[0]) * (a.bbox[3] - a.bbox[1]));
const body = out.map((m) => `  [${JSON.stringify(m.label)}, ${JSON.stringify(m.title)}, '${m.fmt}', [${m.bbox.join(', ')}], ${m.maxZ}],`).join('\n');
writeFileSync(
  new URL('../src/space/mars-mosaics.ts', import.meta.url),
  `// Generated by scripts/mars-mosaics.mjs from NASA Mars Trek (${new Date().toISOString().slice(0, 10)}) – do not edit.
// Regional HiRISE / CTX image mosaics: [label, title, format, [west, south, east, north], finest level].
// Tiles: https://trek.nasa.gov/tiles/Mars/EQ/<label>/1.0.0/default/default028mm/{z}/{row}/{col}.<format>

export type TrekMosaic = [label: string, title: string, format: string, bbox: [number, number, number, number], maxZ: number];

export const MARS_MOSAICS: TrekMosaic[] = [
${body}
];
`,
);
console.log(`${out.length} mosaics`);
